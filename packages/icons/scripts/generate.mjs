import { watch } from "node:fs";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { basename, join } from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "oxfmt";
import { optimize } from "svgo";

const root = fileURLToPath(new URL("../", import.meta.url));
const sourceDirectory = join(root, "svg");
const outputDirectory = join(root, "src/generated");
const check = process.argv.includes("--check");
const watching = process.argv.includes("--watch");
const namePattern = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;
const banner = "// Generated by scripts/generate.mjs. Do not edit.\n";

function compareNames(left, right) {
  if (left === right) return 0;
  return left < right ? -1 : 1;
}

async function collect(directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await collect(path)));
    else if (entry.isFile() && entry.name.endsWith(".svg")) files.push(path);
  }
  return files.sort(compareNames);
}

async function formatSource(fileName, source) {
  const result = await format(fileName, banner + source, { printWidth: 100 });
  if (result.errors.length > 0) throw new Error(`Cannot format generated ${fileName}`);
  return result.code;
}

async function generate() {
  const files = await collect(sourceDirectory);
  if (files.length === 0) throw new Error("No SVG icons found.");
  const definitions = {};
  const symbols = [];
  for (const path of files) {
    const name = basename(path, ".svg");
    if (!namePattern.test(name)) throw new Error(`Invalid icon name: ${name}`);
    if (Object.hasOwn(definitions, name)) throw new Error(`Duplicate icon name: ${name}`);
    const id = `erbium-icon-${name}`;
    let viewBox;
    const result = optimize(await readFile(path, "utf8"), {
      path,
      plugins: [
        "removeDoctype",
        "removeXMLProcInst",
        "removeComments",
        "cleanupAttrs",
        { name: "prefixIds", params: { prefix: id, prefixClassNames: false } },
        {
          name: "icon-symbol",
          fn: () => ({
            element: {
              enter(node, parent) {
                if (parent.type !== "root") return;
                if (node.name !== "svg") throw new Error(`Expected SVG root: ${path}`);
                viewBox = node.attributes.viewBox;
                const coordinates = viewBox?.trim().split(/\s+/).map(Number);
                if (
                  !coordinates ||
                  coordinates.length !== 4 ||
                  coordinates.some((coordinate) => !Number.isFinite(coordinate)) ||
                  coordinates[2] <= 0 ||
                  coordinates[3] <= 0
                ) {
                  throw new Error(`Expected a valid viewBox: ${path}`);
                }
                node.name = "symbol";
                node.attributes.id = id;
                delete node.attributes.xmlns;
                delete node.attributes.width;
                delete node.attributes.height;
              },
            },
          }),
        },
      ],
    });
    if (!viewBox) throw new Error(`Missing SVG root: ${path}`);
    definitions[name] = { id, viewBox };
    symbols.push(result.data);
  }
  const names = Object.keys(definitions).sort(compareNames);
  const sortedDefinitions = Object.fromEntries(names.map((name) => [name, definitions[name]]));
  const spriteSheet = `<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join("\n")}\n</svg>\n`;
  const outputs = new Map([
    [
      "index.js",
      await formatSource(
        "index.js",
        `export const iconNames = ${JSON.stringify(names)};\nexport const iconDefinitions = ${JSON.stringify(sortedDefinitions)};\n`,
      ),
    ],
    [
      "index.d.ts",
      await formatSource(
        "index.d.ts",
        `export declare const iconNames: readonly ${JSON.stringify(names)};\nexport type IconName = (typeof iconNames)[number];\nexport type IconSymbolId = \`erbium-icon-\${IconName}\`;\nexport declare const iconDefinitions: { readonly [Name in IconName]: { readonly id: \`erbium-icon-\${Name}\`; readonly viewBox: string } };\n`,
      ),
    ],
    ["sprite.svg", spriteSheet],
    [
      "sprite.js",
      await formatSource(
        "sprite.js",
        `export const spriteSheet = ${JSON.stringify(spriteSheet)};\n`,
      ),
    ],
    [
      "sprite.d.ts",
      await formatSource("sprite.d.ts", "export declare const spriteSheet: string;\n"),
    ],
  ]);
  const stale = [];
  if (!check) await mkdir(outputDirectory, { recursive: true });
  for (const [name, content] of outputs) {
    const destination = join(outputDirectory, name);
    const previous = await readFile(destination, "utf8").catch((error) => {
      if (error.code === "ENOENT") return undefined;
      throw error;
    });
    if (previous === content) continue;
    if (check) stale.push(name);
    else await writeFile(destination, content);
  }
  if (stale.length > 0) {
    throw new Error(`Stale icon outputs: ${stale.join(", ")}. Run bun run icons:generate.`);
  }
  process.stdout.write(`${check ? "Checked" : "Generated"} ${names.length} icons.\n`);
}

if (check && watching) throw new Error("Use either --check or --watch.");
await generate();
if (watching) {
  let timer;
  let queue = Promise.resolve();
  watch(sourceDirectory, { recursive: true }, () => {
    clearTimeout(timer);
    timer = setTimeout(() => {
      queue = queue.then(generate).catch((error) => {
        process.stderr.write(`${error.message}\n`);
      });
    }, 100);
  });
  process.stdout.write("Watching SVG sources.\n");
}
