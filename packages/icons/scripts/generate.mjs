import { watch } from "node:fs";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { basename, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "oxfmt";
import { optimize } from "svgo";

const root = fileURLToPath(new URL("../", import.meta.url));
const sourceDirectory = join(root, "svg");
const outputDirectory = join(root, "src/generated");
const check = process.argv.includes("--check");
const watching = process.argv.includes("--watch");
const namePattern = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;
const banner = "// Generated by scripts/generate.mjs. Do not edit.\n";

const compareNames = (left, right) => {
  if (left === right) {
    return 0;
  }

  return left < right ? -1 : 1;
};

const collect = async (directory) => {
  const files = [];

  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);

    if (entry.isDirectory()) {
      files.push(...(await collect(path)));
    } else if (entry.isFile() && entry.name.endsWith(".svg")) {
      files.push(path);
    }
  }

  return files.sort(compareNames);
};

const formatSource = async (fileName, source) => {
  const result = await format(fileName, banner + source, { printWidth: 100 });

  if (result.errors.length > 0) {
    throw new Error(`Cannot format generated ${fileName}`);
  }

  return result.code;
};

const generate = async () => {
  const files = await collect(sourceDirectory);

  if (files.length === 0) {
    throw new Error("No SVG icons found.");
  }

  const definitions = {};
  const symbols = [];
  const groups = {};

  for (const path of files) {
    const name = basename(path, ".svg");
    const group = relative(sourceDirectory, path).split(sep).slice(0, -1)[0];

    if (!group) {
      throw new Error(`Icons must live in a group directory: ${path}`);
    }

    if (!namePattern.test(name)) {
      throw new Error(`Invalid icon name: ${name}`);
    }

    if (Object.hasOwn(definitions, name)) {
      throw new Error(`Duplicate icon name: ${name}`);
    }

    const id = `erbium-icon-${name}`;
    let viewBox;

    const result = optimize(await readFile(path, "utf-8"), {
      path,
      plugins: [
        "removeDoctype",
        "removeXMLProcInst",
        "removeComments",
        "cleanupAttrs",
        { name: "prefixIds", params: { prefix: id, prefixClassNames: false } },
        {
          fn: () => ({
            element: {
              enter(node, parent) {
                if (parent.type !== "root") {
                  return;
                }

                if (node.name !== "svg") {
                  throw new Error(`Expected SVG root: ${path}`);
                }

                viewBox = node.attributes.viewBox;
                const coordinates = viewBox?.trim().split(/\s+/).map(Number);

                if (
                  !coordinates ||
                  coordinates.length !== 4 ||
                  coordinates.some((coordinate) => !Number.isFinite(coordinate)) ||
                  coordinates[2] <= 0 ||
                  coordinates[3] <= 0
                ) {
                  throw new Error(`Expected a valid viewBox: ${path}`);
                }

                node.name = "symbol";
                node.attributes.id = id;
                delete node.attributes.xmlns;
                delete node.attributes.width;
                delete node.attributes.height;
              },
            },
          }),
          name: "icon-symbol",
        },
      ],
    });

    if (!viewBox) {
      throw new Error(`Missing SVG root: ${path}`);
    }

    definitions[name] = { id, viewBox };
    (groups[group] ??= { names: [], symbols: [] }).names.push(name);
    groups[group].symbols.push(result.data);
    symbols.push(result.data);
  }

  const names = Object.keys(definitions).sort(compareNames);
  const sortedDefinitions = Object.fromEntries(names.map((name) => [name, definitions[name]]));
  const sheet = (list) => `<svg xmlns="http://www.w3.org/2000/svg">\n${list.join("\n")}\n</svg>\n`;
  const spriteSheet = sheet(symbols);
  const groupNames = Object.keys(groups).sort(compareNames);

  const iconGroups = Object.fromEntries(
    groupNames.map((group) => [group, groups[group].names.sort(compareNames)]),
  );

  const spriteSheets = Object.fromEntries(
    groupNames.map((group) => [group, sheet(groups[group].symbols)]),
  );

  const outputs = new Map([
    [
      "index.js",
      await formatSource(
        "index.js",
        `export const iconNames = ${JSON.stringify(names)};\nexport const iconGroups = ${JSON.stringify(iconGroups)};\nexport const iconDefinitions = ${JSON.stringify(sortedDefinitions)};\n`,
      ),
    ],
    [
      "index.d.ts",
      await formatSource(
        "index.d.ts",
        `export declare const iconNames: readonly ${JSON.stringify(names)};\nexport declare const iconGroups: { ${groupNames.map((group) => `readonly ${JSON.stringify(group)}: readonly ${JSON.stringify(iconGroups[group])}`).join("; ")} };\nexport type IconGroup = keyof typeof iconGroups;\nexport type IconName = (typeof iconNames)[number];\nexport type IconSymbolId = \`erbium-icon-\${IconName}\`;\nexport declare const iconDefinitions: { readonly [Name in IconName]: { readonly id: \`erbium-icon-\${Name}\`; readonly viewBox: string } };\n`,
      ),
    ],
    ["sprite.svg", spriteSheet],
    [
      "sprite.js",
      await formatSource(
        "sprite.js",
        `export const spriteSheet = ${JSON.stringify(spriteSheet)};\nexport const spriteSheets = ${JSON.stringify(spriteSheets)};\n`,
      ),
    ],
    [
      "sprite.d.ts",
      await formatSource(
        "sprite.d.ts",
        `export declare const spriteSheet: string;\nexport declare const spriteSheets: { ${groupNames.map((group) => `readonly ${JSON.stringify(group)}: string`).join("; ")} };\n`,
      ),
    ],
  ]);

  const stale = [];

  if (!check) {
    await mkdir(outputDirectory, { recursive: true });
  }

  for (const [name, content] of outputs) {
    const destination = join(outputDirectory, name);

    const previous = await readFile(destination, "utf-8").catch((error) => {
      if (error.code === "ENOENT") {
        return;
      }

      throw error;
    });

    if (previous === content) {
      continue;
    }

    if (check) {
      stale.push(name);
    } else {
      await writeFile(destination, content);
    }
  }

  if (stale.length > 0) {
    throw new Error(`Stale icon outputs: ${stale.join(", ")}. Run bun run icons:generate.`);
  }

  process.stdout.write(`${check ? "Checked" : "Generated"} ${names.length} icons.\n`);
};

if (check && watching) {
  throw new Error("Use either --check or --watch.");
}

await generate();

if (watching) {
  let timer;
  let queue = Promise.resolve();
  watch(sourceDirectory, { recursive: true }, () => {
    clearTimeout(timer);
    timer = setTimeout(() => {
      queue = queue.then(generate).catch((error) => {
        process.stderr.write(`${error.message}\n`);
      });
    }, 100);
  });
  process.stdout.write("Watching SVG sources.\n");
}
