import { watch } from "node:fs";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "oxfmt";
import { optimize } from "svgo";

/** @typedef {{ id: string, viewBox: string }} IconDefinition */
/** @typedef {{ names: string[], symbols: string[] }} IconGroup */

const root = fileURLToPath(new URL("../", import.meta.url));
const sourceDirectory = path.join(root, "svg");
const outputDirectory = path.join(root, "src/generated");
const check = process.argv.includes("--check");
const watching = process.argv.includes("--watch");
const namePattern = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/u;
const whitespace = /\s+/u;
const banner = "// Generated by scripts/generate.mjs. Do not edit.\n";

/**
 * Orders names by code unit, independent of the host locale.
 * @param {string} left - The first name.
 * @param {string} right - The second name.
 * @returns {number} A negative, zero, or positive sort order.
 */
const compareNames = (left, right) => {
  if (left === right) {
    return 0;
  }

  return left < right ? -1 : 1;
};

/**
 * @param {string[]} list - Optimized symbol markup.
 * @returns {string} An SVG document holding the symbols.
 */
const sheet = (list) => `<svg xmlns="http://www.w3.org/2000/svg">\n${list.join("\n")}\n</svg>\n`;

/**
 * Finds every SVG file below a directory.
 * @param {string} directory - The directory to walk.
 * @returns {Promise<string[]>} Absolute file paths in name order.
 */
const collect = async (directory) => {
  const entries = await readdir(directory, { withFileTypes: true });

  const nested = await Promise.all(
    entries.map(async (entry) => {
      const file = path.join(directory, entry.name);

      if (entry.isDirectory()) {
        return await collect(file);
      }

      return entry.isFile() && entry.name.endsWith(".svg") ? [file] : [];
    }),
  );

  return nested.flat().toSorted(compareNames);
};

/**
 * @param {string} fileName - The generated file name, which picks the parser.
 * @param {string} source - The unformatted source.
 * @returns {Promise<string>} The formatted source with the generated banner.
 */
const formatSource = async (fileName, source) => {
  const result = await format(fileName, banner + source, { printWidth: 100 });

  if (result.errors.length > 0) {
    throw new Error(`Cannot format generated ${fileName}`);
  }

  return result.code;
};

/**
 * @param {string} file - A file path.
 * @param {string} content - The expected contents.
 * @returns {Promise<boolean>} Whether the file exists with exactly these contents.
 */
const isCurrent = async (file, content) => {
  try {
    return (await readFile(file, "utf-8")) === content;
  } catch (error) {
    if (error instanceof Error && "code" in error && error.code === "ENOENT") {
      return false;
    }

    throw error;
  }
};

/**
 * @param {string | undefined} viewBox - A viewBox attribute value.
 * @returns {boolean} Whether it holds four finite numbers with a positive size.
 */
const isValidViewBox = (viewBox) => {
  const coordinates = viewBox?.trim().split(whitespace).map(Number);

  if (coordinates?.length !== 4) {
    return false;
  }

  return (
    coordinates.every((coordinate) => Number.isFinite(coordinate)) &&
    coordinates.slice(2).every((size) => size > 0)
  );
};

/**
 * Turns one SVG file into a sprite symbol.
 * @param {string} file - The SVG file path.
 * @param {string} source - The SVG file contents.
 * @param {string} id - The symbol id.
 * @returns {{ data: string, viewBox: string }} The symbol markup and its viewBox.
 */
const toSymbol = (file, source, id) => {
  /** @type {string | undefined} */
  let viewBox;

  const result = optimize(source, {
    path: file,
    plugins: [
      "removeDoctype",
      "removeXMLProcInst",
      "removeComments",
      "cleanupAttrs",
      { name: "prefixIds", params: { prefix: id, prefixClassNames: false } },
      {
        fn: () => ({
          element: {
            enter(node, parent) {
              if (parent.type !== "root") {
                return;
              }

              if (node.name !== "svg") {
                throw new Error(`Expected SVG root: ${file}`);
              }

              ({ viewBox } = node.attributes);

              if (!isValidViewBox(viewBox)) {
                throw new Error(`Expected a valid viewBox: ${file}`);
              }

              node.name = "symbol";
              node.attributes.id = id;
              delete node.attributes.xmlns;
              delete node.attributes.width;
              delete node.attributes.height;
            },
          },
        }),
        name: "icon-symbol",
      },
    ],
  });

  if (viewBox === undefined || viewBox === "") {
    throw new Error(`Missing SVG root: ${file}`);
  }

  return { data: result.data, viewBox };
};

const generate = async () => {
  const files = await collect(sourceDirectory);

  if (files.length === 0) {
    throw new Error("No SVG icons found.");
  }

  const sources = await Promise.all(files.map(async (file) => await readFile(file, "utf-8")));

  /** @type {Record<string, IconDefinition>} */
  const definitions = {};

  /** @type {string[]} */
  const symbols = [];

  /** @type {Record<string, IconGroup>} */
  const groups = {};

  for (const [index, file] of files.entries()) {
    const name = path.basename(file, ".svg");
    const [group] = path.relative(sourceDirectory, file).split(path.sep).slice(0, -1);

    if (group === undefined || group === "") {
      throw new Error(`Icons must live in a group directory: ${file}`);
    }

    if (!namePattern.test(name)) {
      throw new Error(`Invalid icon name: ${name}`);
    }

    if (Object.hasOwn(definitions, name)) {
      throw new Error(`Duplicate icon name: ${name}`);
    }

    const id = `erbium-icon-${name}`;
    const { data, viewBox } = toSymbol(file, sources[index] ?? "", id);

    definitions[name] = { id, viewBox };
    const entry = groups[group] ?? { names: [], symbols: [] };
    groups[group] = entry;
    entry.names.push(name);
    entry.symbols.push(data);
    symbols.push(data);
  }

  const names = Object.keys(definitions).toSorted(compareNames);
  const sortedDefinitions = Object.fromEntries(names.map((name) => [name, definitions[name]]));
  const spriteSheet = sheet(symbols);
  const groupNames = Object.keys(groups).toSorted(compareNames);

  const iconGroups = Object.fromEntries(
    groupNames.map((group) => [group, (groups[group]?.names ?? []).toSorted(compareNames)]),
  );

  const spriteSheets = Object.fromEntries(
    groupNames.map((group) => [group, sheet(groups[group]?.symbols ?? [])]),
  );

  const outputs = new Map([
    [
      "index.js",
      await formatSource(
        "index.js",
        `export const iconNames = ${JSON.stringify(names)};\nexport const iconGroups = ${JSON.stringify(iconGroups)};\nexport const iconDefinitions = ${JSON.stringify(sortedDefinitions)};\n`,
      ),
    ],
    [
      "index.d.ts",
      await formatSource(
        "index.d.ts",
        `export declare const iconNames: readonly ${JSON.stringify(names)};\nexport declare const iconGroups: { ${groupNames.map((group) => `readonly ${JSON.stringify(group)}: readonly ${JSON.stringify(iconGroups[group])}`).join("; ")} };\nexport type IconGroup = keyof typeof iconGroups;\nexport type IconName = (typeof iconNames)[number];\nexport type IconSymbolId = \`erbium-icon-\${IconName}\`;\nexport declare const iconDefinitions: { readonly [Name in IconName]: { readonly id: \`erbium-icon-\${Name}\`; readonly viewBox: string } };\n`,
      ),
    ],
    ["sprite.svg", spriteSheet],
    [
      "sprite.js",
      await formatSource(
        "sprite.js",
        `export const spriteSheet = ${JSON.stringify(spriteSheet)};\nexport const spriteSheets = ${JSON.stringify(spriteSheets)};\n`,
      ),
    ],
    [
      "sprite.d.ts",
      await formatSource(
        "sprite.d.ts",
        `export declare const spriteSheet: string;\nexport declare const spriteSheets: { ${groupNames.map((group) => `readonly ${JSON.stringify(group)}: string`).join("; ")} };\n`,
      ),
    ],
  ]);

  if (!check) {
    await mkdir(outputDirectory, { recursive: true });
  }

  // Each output is its own file, so they are compared and written in parallel.
  // The stale list keeps the output order.
  const changed = await Promise.all(
    [...outputs].map(async ([name, content]) => {
      const destination = path.join(outputDirectory, name);

      if (await isCurrent(destination, content)) {
        return [];
      }

      if (!check) {
        await writeFile(destination, content);
      }

      return [name];
    }),
  );

  const stale = changed.flat();

  if (check && stale.length > 0) {
    throw new Error(`Stale icon outputs: ${stale.join(", ")}. Run bun run icons:generate.`);
  }

  process.stdout.write(`${check ? "Checked" : "Generated"} ${names.length} icons.\n`);
};

/** Regenerates and reports a failure without stopping the watcher. */
const regenerate = async () => {
  try {
    await generate();
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
  }
};

if (check && watching) {
  throw new Error("Use either --check or --watch.");
}

await generate();

if (watching) {
  /** @type {NodeJS.Timeout | undefined} */
  let timer;

  /** @type {Promise<void>} */
  let queue = Promise.resolve();

  watch(sourceDirectory, { recursive: true }, () => {
    clearTimeout(timer);

    timer = setTimeout(() => {
      queue = queue.then(regenerate);
    }, 100);
  });

  process.stdout.write("Watching SVG sources.\n");
}
