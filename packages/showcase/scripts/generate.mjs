import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { readFile, readdir, unlink, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const sections = JSON.parse(
  await readFile(new URL("../../content/src/sections.json", import.meta.url), "utf-8"),
);

const classifiedNames = sections.flatMap((section) => section.names);

if (new Set(classifiedNames).size !== classifiedNames.length) {
  throw new Error("Showcase names must belong to exactly one documentation section");
}

const root = dirname(import.meta.dirname);
const check = process.argv.includes("--check");

export const output = async (path, content, json = false) => {
  if (check) {
    const actual = await readFile(path, "utf-8").catch(() => "");

    const normalize = (value) =>
      json
        ? JSON.stringify(JSON.parse(value || "null"))
        : value.replaceAll(/,\s*(?=[}\]])/g, "").replaceAll(/\s+/g, "");

    if (normalize(actual) !== normalize(content)) {
      throw new Error(`Generated file is stale: ${path}`);
    }
  } else {
    await writeFile(path, content);
  }
};

const manifest = [];

for (const entry of (await readdir(join(root, "src"), { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .sort((a, b) => a.name.localeCompare(b.name))) {
  const source = await readFile(join(root, "src", entry.name, "catalog.tsx"), "utf-8").catch(
    () => null,
  );

  if (!source) {
    continue;
  }

  const section = sections.find((section) => section.names.includes(entry.name));

  if (!section) {
    throw new Error(`Missing documentation classification: ${entry.name}`);
  }

  const markdown = await readFile(
    join(root, "../content/components", entry.name, "index.md"),
    "utf-8",
  );

  const heading = /^title:[ \t]*(.+)$/m.exec(markdown)?.[1];

  if (!heading) {
    throw new Error(`Missing Markdown title: ${entry.name}`);
  }

  const displayTitle = heading.startsWith('"') ? JSON.parse(heading) : heading.trim();
  const title = `${section.title}/${displayTitle}`;
  const variants = [];

  for (const match of source.matchAll(/export const (\w+)(?:\s*:[^=]+)?\s*=/g)) {
    const exportName = match[1];

    const slug = new RegExp(`import ${exportName}Example from "\\./variants/([^"/]+)"`).exec(
      source,
    )?.[1];

    if (!slug) {
      throw new Error(`Missing variant file: ${entry.name}/${exportName}`);
    }

    const markdown = await readFile(
      join(root, "../content/components", entry.name, `${slug}.md`),
      "utf-8",
    );

    const display = JSON.parse(
      /^title:\s*(".*")$/m.exec(markdown)?.[1] ?? JSON.stringify(exportName),
    );

    variants.push({
      exportName,
      slug,
      source: `src/${entry.name}/variants/${slug}.tsx`,
      title: display,
    });
  }

  manifest.push({ name: entry.name, title, variants });
  const adapter = `// Generated by @erbium/showcase. Edit packages/showcase/src/${entry.name} instead.\nimport meta, * as showcases from "@erbium/showcase/${entry.name}";\nexport default { ...meta, title: ${JSON.stringify(title)} };\n${variants.map((variant) => `export const ${variant.exportName} = { ...showcases.${variant.exportName}, name: ${JSON.stringify(variant.title)} };`).join("\n")}\n`;
  await output(
    join(root, "../../apps/storybook/src/stories", `${entry.name}.stories.tsx`),
    adapter,
  );
}

for (const name of classifiedNames) {
  if (name !== "colors" && !manifest.some((entry) => entry.name === name)) {
    throw new Error(`Documentation classification has no showcase: ${name}`);
  }
}

await output(join(root, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`, true);

process.stdout.write(
  `${check ? "Verified" : "Generated"} ${manifest.length} catalogs and ${manifest.reduce((total, entry) => total + entry.variants.length, 0)} variants.\n`,
);

if (!check) {
  await promisify(execFile)(
    "vp",
    ["fmt", "packages/showcase/manifest.json", "apps/storybook/src/stories", "--write"],
    { cwd: join(root, "../..") },
  );
}

const adapters = join(root, "../../apps/storybook/src/stories");
const expectedAdapters = new Set(manifest.map((entry) => `${entry.name}.stories.tsx`));

for (const file of await readdir(adapters)) {
  if (!file.endsWith(".stories.tsx") || expectedAdapters.has(file)) {
    continue;
  }

  const path = join(adapters, file);

  if (!(await readFile(path, "utf-8")).startsWith("// Generated by @erbium/showcase.")) {
    continue;
  }

  if (check) {
    throw new Error(`Orphaned Storybook adapter: ${path}`);
  }

  await unlink(path);
}
